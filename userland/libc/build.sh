#!/bin/sh
# libc.a: the parts of IRIX's libc that the host C library has no equivalent for (IRIX libc source and all of libgen),
# plus the IRIX functions written here for the host (host/: kernel calls, sysinfo, extended attributes, ...), for i386
# and x86_64, into libc/lib/32 and libc/lib/64.  irixcc and hostcc link it into everything by path, ahead of the host's
# own libc.  The IRIX files are copied from the source tree into a work directory, the recorded source fixes in
# libc/patches are applied there, and they are compiled with libc's internal headers.  Paths literal.
set -e
L=/home/nekron/Projects/irix-657m-src/irix/lib/libc
U=/home/nekron/Projects/irix-work/userland
W=/home/nekron/opt/claude-work/eoe/libc
# Not built: mls/sat_*.c, the audit (SAT) records.  sat_call.c names IRIX fcntl commands the host lacks, and
# sys/sat_compat.h has a typo SGI never compiled ("unsigend long"); audit belongs with the kernel personality.
FILES="locale/nl_error.c locale/nl_usage.c locale/nl_query.c locale/sgi_dofmt.c locale/sgi_sfmtmsg.c
	locale/sgi_ffmtmsg.c locale/pfmt.c locale/vpfmt.c locale/lfmt.c locale/setlabel.c locale/gettxt.c locale/gtxt.c locale/pfmt_data.c locale/_loc_data.c locale/_ctype.c locale/pfmt_print.c locale/vlfmt.c
	strings/wscat.c strings/wschr.c strings/wscmp.c strings/wscpy.c strings/wscspn.c strings/wslen.c strings/wsncat.c
	strings/wsncmp.c strings/wsncpy.c strings/wspbrk.c strings/wsrchr.c strings/wsspn.c strings/wstostr.c
	gen/cftime.c gen/mkdev.c gen/devname.c gen/getprent.c gen/getopt.c gen/opt_data.c gen/getinvent.c gen/scaninvent.c
	mls/acl_posix.c mls/cap_acquire.c mls/cap_env.c mls/cap_posix.c mls/getcapabilitybyname.c mls/mac_cleared.c mls/mac_dup.c
	mls/mac_label.c mls/mac_lbldevs.c mls/mac_posix.c mls/mac_util.c"
# libc's synonyms.h renames public names to libc-internal ones (munmap -> _munmap).  A wrapper of the same name, found
# first, includes it and then undoes every rename whose public name the host C library or libm provides, so calls
# reach the host; the IRIX-only names stay renamed on both the defining and the calling side.
mkdir -p $W/syn
{
	echo '/* generated by libc/build.sh: libc'"'"'s synonyms.h minus the names the host provides */'
	echo '#include_next <synonyms.h>'
	nm -D --defined-only /lib64/libc.so.6 /lib64/libm.so.6 2>/dev/null | awk '{print $3}' | sed 's/@.*//' | sort -u > $W/syn/host.txt
	sed -n 's/^#define[[:space:]]\{1,\}\([A-Za-z_][A-Za-z0-9_]*\)[[:space:]]\{1,\}_.*/\1/p' $L/inc/synonyms.h | sort -u | comm -12 - $W/syn/host.txt | grep -v -x -e sys_errlist -e sys_nerr -e getopt -e optind -e optarg -e opterr -e optopt | sed 's/^/#undef /'   # (the prelude gives those IRIX's names)
} > $W/syn/synonyms.h
# IRIX headers that libc's own sources need instead of the host's (the ctype classes _U, _L, ... and their table)
mkdir -p $W/irixhdr
cp /home/nekron/Projects/irix-657m-src/eoe/include/ctype.h $W/irixhdr/
rm -rf $W/src
mkdir -p $W/src
for f in $FILES; do cp $L/src/$f $W/src/; done
mkdir -p $W/locale && cp $L/src/locale/*.h $W/locale/    # (gen/getopt.c includes "../locale/pfmt_data.h")
cp $L/src/locale/*.h $L/src/mls/*.h $L/src/gen/*.h $W/src/                    # the directory's own headers (pfmt_data.h, ...)
for p in $U/libc/patches/*.patch; do (cd $W/src && patch -s -p1 < $p); done
# libgen (eoe/lib/libgen): every source file, in a directory of its own (it has its own synonyms.h)
G=/home/nekron/Projects/irix-657m-src/eoe/lib/libgen/src
rm -rf $W/gen
mkdir -p $W/gen
cp $G/*.c $G/*.h $W/gen/
# libgen's synonyms.h does libc's renaming too (stat -> _stat): wrapped the same way, minus the host's names
mv $W/gen/synonyms.h $W/gen/synonyms_libgen.h
{
	echo '/* generated by libc/build.sh: libgen'"'"'s synonyms.h minus the names the host provides */'
	echo '#include "synonyms_libgen.h"'
	# (libgen's own functions keep IRIX's names and semantics even where the host has one: basename, dirname)
	grep -ho 'pragma weak [A-Za-z_0-9]*' $W/gen/*.c | awk '{print $3}' | sort -u > $W/gen/.own
	sed -n 's/^#define[[:space:]]\{1,\}\([A-Za-z_][A-Za-z0-9_]*\)[[:space:]]\{1,\}_.*/\1/p' $W/gen/synonyms_libgen.h | sort -u | comm -12 - $W/syn/host.txt | comm -23 - $W/gen/.own | sed 's/^/#undef /'
} > $W/gen/synonyms.h
for m in 32 64; do
	mkdir -p $W/$m
	for f in $FILES; do
		n=$(basename $f .c)
		gcc -m$m -O1 -fPIC -std=gnu89 -w -fcommon -fno-strict-aliasing -U_FORTIFY_SOURCE -include $U/compat/include/prelude.h \
			-I$U/compat/include -I$U/compat/irix-include -I$W/syn -I$L/inc -I$W/irixhdr -idirafter /home/nekron/opt/claude-work/eoe/root/usr/include \
			-c $W/src/$n.c -o $W/$m/$n.o
	done
	for f in $W/gen/*.c; do
		n=$(basename $f .c)
		gcc -m$m -O1 -fPIC -std=gnu89 -w -fcommon -fno-strict-aliasing -U_FORTIFY_SOURCE -include $U/compat/include/prelude.h \
			-I$U/compat/include -I$U/compat/irix-include -I$W/gen -idirafter /home/nekron/opt/claude-work/eoe/root/usr/include \
			-c $f -o $W/$m/gen_$n.o
	done
	for f in $U/libc/host/*.c; do
		n=$(basename $f .c)
		gcc -m$m -O1 -fPIC -w -c $f -o $W/$m/host_$n.o
	done
	mkdir -p $U/libc/lib/$m
	rm -f $U/libc/lib/$m/libc.a
	ar rcs $U/libc/lib/$m/libc.a $W/$m/*.o
done
echo "libc ready"
