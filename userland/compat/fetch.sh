#!/bin/sh
# Copy the IRIX headers the host lacks into compat/irix-include (not committed).  Paths literal.
set -e
S=/home/nekron/Projects/irix-657m-src
D=/home/nekron/Projects/irix-work/userland/compat/irix-include
mkdir -p $D
mkdir -p $D/sys
cp $S/eoe/include/tzfile.h $D/
cp $S/irix/kern/sys/sysmp.h $S/irix/kern/sys/syssgi.h $D/sys/
# IRIX versions that must win over the host's: they carry IRIX's own extensions (MM_REASON, DEF_NLSPATH)
cp $S/eoe/include/fmtmsg.h $S/eoe/include/nl_types.h $D/
# IRIX's capability and ACL interfaces (cap_acquire, struct _cap_struct, CAP_MAC_READ, struct acl) instead of
# libcap's and libacl's headers
cp $S/irix/kern/sys/capability.h $S/irix/kern/sys/acl.h $D/sys/
# sysconf names IRIX has and the host lacks: offset by 0x4000 so they never collide with the host's numbers;
# irix_k_sysconf (compat/lib) passes them to the kernel as syssgi(SGI_SYSCONF, name), as IRIX's sysconf does
{
	echo '/* generated by fetch.sh from irix/kern/sys/unistd.h: IRIX-only sysconf names, numbered IRIX + 0x4000 */'
	echo '#define IRIX_SC_BASE 0x4000'
	printf '#include <unistd.h>\n' | gcc -E -dM -x c - | sed -n 's/^#define \(_SC_[A-Z0-9_]*\) .*/\1/p' | sort -u > $D/.host_sc
	sed -n 's/^#define[[:space:]]\{1,\}\(_SC_[A-Z0-9_]*\)[[:space:]]\{1,\}\([0-9]\{1,\}\).*/\1 \2/p' $S/irix/kern/sys/unistd.h | sort -u -k1,1 | while read -r n v; do
		grep -qx "$n" $D/.host_sc || echo "#define $n (IRIX_SC_BASE + $v)"
	done
	rm -f $D/.host_sc
} > $D/irix_sysconf.h
# _PATH_ names IRIX's <paths.h> has and the host's lacks, with IRIX's values
{
	echo '/* generated by fetch.sh from eoe/include/paths.h: IRIX _PATH_ names the host lacks */'
	printf '#include <paths.h>\n' | gcc -E -dM -x c - | sed -n 's/^#define \(_PATH_[A-Z0-9_]*\) .*/\1/p' | sort -u > $D/.host_path
	grep -E '^#define[[:space:]]+_PATH_[A-Z0-9_]+[[:space:]]' $S/eoe/include/paths.h | while read -r d n v; do
		grep -qx "$n" $D/.host_path || echo "#ifndef $n
#define $n $v
#endif"
	done
	rm -f $D/.host_path
} > $D/irix_paths.h
