#!/bin/sh
# libirixc.a: IRIX libc source files the host C library has no equivalent for, and all of libgen, compiled for i386 and x86_64 into
# compat/lib/32 and compat/lib/64 (linked into everything by irixcc and hostcc).  The files are copied from the
# source tree into a work directory, the recorded source fixes in patches/libc are applied there, and they are
# compiled with libc's internal headers.  Paths literal.
set -e
L=/home/nekron/Projects/irix-657m-src/irix/lib/libc
U=/home/nekron/Projects/irix-work/userland
W=/home/nekron/opt/claude-work/eoe/irixc
FILES="locale/nl_error.c locale/nl_usage.c locale/nl_query.c locale/sgi_dofmt.c locale/sgi_sfmtmsg.c
	locale/sgi_ffmtmsg.c locale/pfmt.c locale/vpfmt.c locale/lfmt.c locale/setlabel.c locale/gettxt.c locale/gtxt.c locale/pfmt_data.c locale/_loc_data.c locale/_ctype.c locale/pfmt_print.c locale/vlfmt.c
	strings/wscat.c strings/wschr.c strings/wscmp.c strings/wscpy.c strings/wscspn.c strings/wslen.c strings/wsncat.c
	strings/wsncmp.c strings/wsncpy.c strings/wspbrk.c strings/wsrchr.c strings/wsspn.c strings/wstostr.c"
# libc's synonyms.h renames public names to libc-internal ones (munmap -> _munmap).  A wrapper of the same name, found
# first, includes it and then undoes every rename whose public name the host C library or libm provides, so calls
# reach the host; the IRIX-only names stay renamed on both the defining and the calling side.
mkdir -p $W/syn
{
	echo '/* generated by build-irixc.sh: libc'"'"'s synonyms.h minus the names the host provides */'
	echo '#include_next <synonyms.h>'
	nm -D --defined-only /lib64/libc.so.6 /lib64/libm.so.6 2>/dev/null | awk '{print $3}' | sed 's/@.*//' | sort -u > $W/syn/host.txt
	sed -n 's/^#define[[:space:]]\{1,\}\([A-Za-z_][A-Za-z0-9_]*\)[[:space:]]\{1,\}_.*/\1/p' $L/inc/synonyms.h | sort -u | comm -12 - $W/syn/host.txt | grep -v -x -e sys_errlist -e sys_nerr | sed 's/^/#undef /'   # (the prelude gives those IRIX's names)
} > $W/syn/synonyms.h
# IRIX headers that libc's own sources need instead of the host's (the ctype classes _U, _L, ... and their table)
mkdir -p $W/irixhdr
cp /home/nekron/Projects/irix-657m-src/eoe/include/ctype.h $W/irixhdr/
rm -rf $W/src
mkdir -p $W/src
for f in $FILES; do cp $L/src/$f $W/src/; done
cp $L/src/locale/*.h $W/src/                    # the directory's own headers (pfmt_data.h, ...)
for p in $U/patches/libc/*.patch; do (cd $W/src && patch -s -p1 < $p); done
# libgen (eoe/lib/libgen): every source file, in a directory of its own (it has its own synonyms.h)
G=/home/nekron/Projects/irix-657m-src/eoe/lib/libgen/src
rm -rf $W/gen
mkdir -p $W/gen
cp $G/*.c $G/*.h $W/gen/
for m in 32 64; do
	mkdir -p $W/$m
	for f in $FILES; do
		n=$(basename $f .c)
		gcc -m$m -O1 -fPIC -std=gnu89 -w -fcommon -fno-strict-aliasing -U_FORTIFY_SOURCE -include $U/compat/include/prelude.h \
			-I$U/compat/include -I$U/compat/irix-include -I$W/syn -I$L/inc -I$W/irixhdr -idirafter /home/nekron/opt/claude-work/eoe/root/usr/include \
			-c $W/src/$n.c -o $W/$m/$n.o
	done
	for f in $W/gen/*.c; do
		n=$(basename $f .c)
		gcc -m$m -O1 -fPIC -std=gnu89 -w -fcommon -fno-strict-aliasing -U_FORTIFY_SOURCE -include $U/compat/include/prelude.h \
			-I$U/compat/include -I$U/compat/irix-include -I$W/gen -idirafter /home/nekron/opt/claude-work/eoe/root/usr/include \
			-c $f -o $W/$m/gen_$n.o
	done
	rm -f $U/compat/lib/$m/libirixc.a
	ar rcs $U/compat/lib/$m/libirixc.a $W/$m/*.o
done
echo "libirixc ready"
