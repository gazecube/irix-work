/*
 * Public Motif symbols live in libXm.so.  Their implementation shares the
 * single host/guest state owned by libXt.so, so these i386 tail thunks preserve
 * the caller's stack and return registers exactly while crossing the DSO
 * boundary.
 */
#define IRIX_XM_FORWARD(name) \
    __asm__(".text\n" \
            ".globl " #name "\n" \
            ".type " #name ",@function\n" \
            #name ":\n" \
            "pushl %ebx\n" \
            "call 1f\n" \
            "1: popl %ebx\n" \
            "addl $_GLOBAL_OFFSET_TABLE_+(.-1b), %ebx\n" \
            "movl irix_hostabi_impl_" #name "@GOT(%ebx), %eax\n" \
            "popl %ebx\n" \
            "jmp *%eax\n")

