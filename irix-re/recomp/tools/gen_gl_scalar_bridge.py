#!/usr/bin/env python3
"""Generate the by-value OpenGL entry points of the IRIX GL bridge.

Reads the host GL headers and emits one guest-ABI wrapper per listed function
whose parameters are all scalars (N32: integers in a0..a7, floats/doubles in
$f12..$f19 by argument slot).  Functions taking pointers are written by hand
in IrixGlBridge.c.
"""
import re
import sys

VEC = re.compile(
    r"^gl(Color|Normal|Vertex|TexCoord|RasterPos|Index|EdgeFlag|EvalCoord)([1-4])?"
    r"(ub|us|ui|b|s|i|f|d)?v$")
HEADERS = ["/usr/include/GL/gl.h", "/usr/include/GL/glext.h"]
PROTO = re.compile(
    r"^GLAPI[ \t]+([^\n#(]+?)[ \t]+(?:GL)?APIENTRY[ \t]+(\w+)[ \t]*\(([^;#]*?)\)[ \t]*;", re.M)


def load_protos():
    out = {}
    for h in HEADERS:
        text = open(h).read()
        for ret, name, args in PROTO.findall(text):
            if "#" in ret or "#" in args or "(" in ret:
                continue
            out.setdefault(name, (" ".join(ret.split()),
                                  " ".join(args.split())))
    return out


def split_args(args):
    if args in ("", "void"):
        return []
    return [a.strip() for a in args.split(",")]


def arg_kind(a):
    if "*" in a or "[" in a:
        return "ptr"
    t = re.sub(r"\bconst\b", "", a)
    words = t.split()
    ty = " ".join(words[:-1]) if len(words) > 1 else t
    if ty in ("GLfloat", "GLclampf"):
        return "f"
    if ty in ("GLdouble", "GLclampd"):
        return "d"
    return "i"


def main():
    names = [l.strip() for l in open(sys.argv[1]) if l.strip()]
    skip = set(l.strip() for l in open(sys.argv[2])) if len(sys.argv) > 2 else set()
    protos = load_protos()
    body = ["/* Generated by tools/gen_gl_scalar_bridge.py; do not edit. */"]
    table = []
    missing = []
    for name in names:
        if name in skip or not name.startswith("gl") or name.startswith("glX"):
            continue
        if name not in protos:
            missing.append(name)
            continue
        ret, args = protos[name]
        params = split_args(args)
        kinds = [arg_kind(p) for p in params]
        m = VEC.match(name)
        if m and kinds.count("ptr") == 1 and kinds[-1] == "ptr" and ret == "void":
            n = int(m.group(2) or 1)
            suffix = m.group(3) or "ub"
            ety = {"b": "int8_t", "s": "int16_t", "i": "int32_t", "f": "float",
                   "d": "double", "ub": "uint8_t", "us": "uint16_t",
                   "ui": "uint32_t"}[suffix]
            rd = {"b": "gl_rd8", "ub": "gl_rd8", "s": "gl_rd16", "us": "gl_rd16",
                  "i": "gl_rd32", "ui": "gl_rd32", "f": "gl_rdf", "d": "gl_rdd"}[suffix]
            lead = ["I(%d)" % i if k == "i" else ("F(%d)" % i if k == "f" else "D(%d)" % i)
                    for i, k in enumerate(kinds[:-1])]
            ptrslot = len(kinds) - 1
            body.append("static void gl_b_%s(IrixGuestRuntime *rt, IrixGuestCpu *cpu)\n{" % name)
            body.append("    typedef void (*fn_t)(%s);" % args)
            body.append("    fn_t f = (fn_t)gl_proc(\"%s\");" % name)
            body.append("    %s v[%d];" % (ety, n))
            body.append("    IrixGuestAddr p = ARG(%d);" % ptrslot)
            body.append("    int i;")
            body.append("    for (i = 0; i < %d; ++i) v[i] = (%s)%s(rt, p + (IrixGuestAddr)i * sizeof(%s));" % (n, ety, rd, ety))
            body.append("    if (f && !rt->trapped) f(%s);" % ", ".join(lead + ["v"]))
            body.append("    cpu->gpr[2] = 0;\n}")
            table.append(name)
            continue
        if "ptr" in kinds or ret.endswith("*") or len(params) > 8:
            continue
        call = []
        for i, k in enumerate(kinds):
            if k == "f":
                call.append("F(%d)" % i)
            elif k == "d":
                call.append("D(%d)" % i)
            else:
                call.append("I(%d)" % i)
        body.append("static void gl_b_%s(IrixGuestRuntime *rt, IrixGuestCpu *cpu)\n{" % name)
        body.append("    typedef %s (*fn_t)(%s);" % (ret, args))
        body.append("    fn_t f = (fn_t)gl_proc(\"%s\");" % name)
        body.append("    (void)rt;")
        r = ret.replace("const", "").strip()
        if r == "void":
            body.append("    if (f) f(%s);" % ", ".join(call))
            body.append("    cpu->gpr[2] = 0;")
        elif r in ("GLfloat", "GLclampf"):
            body.append("    irix_guest_fpr_set_s(cpu, 0, f ? f(%s) : 0.0f);" % ", ".join(call))
        elif r in ("GLdouble", "GLclampd"):
            body.append("    irix_guest_fpr_set_d(cpu, 0, f ? f(%s) : 0.0);" % ", ".join(call))
        else:
            body.append("    cpu->gpr[2] = f ? (uint32_t)f(%s) : 0u;" % ", ".join(call))
        body.append("}")
        table.append(name)
    body.append("static const struct { const char *name; IrixGuestFunction fn; } gl_scalar_table[] = {")
    for n in table:
        body.append("    { \"%s\", gl_b_%s }," % (n, n))
    body.append("    { 0, 0 }\n};")
    sys.stdout.write("\n".join(body) + "\n")
    sys.stderr.write("scalar wrappers: %d; not in headers: %s\n" % (len(table), " ".join(missing)))


main()
