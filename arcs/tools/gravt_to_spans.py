#!/usr/bin/env python3
"""
Rasterize the GraVT SVG and emit the X64 PROM splash span data.

Span contract: SGI stand/arcs/scripts/graytospans.c.  Each row is a list of
alternating run lengths, the first run being the bright (background) pixels
and possibly zero-length; a run is capped at 255 and a 255 run that continues
is followed by a zero-length run of the other colour.  Pixels > 128 are
background.

Rows are written top-to-bottom; the X64 product boundary
(uefi/prom_product_logo_orientation.c) reverses them once for the original
drawCalligraphy().  Output replaces uefi/prom_product_logo.c.

usage: gravt_to_spans.py assets/GraVT-src.svg uefi/prom_product_logo.c [height]
"""
import base64, subprocess, sys, io, textwrap
from PIL import Image, ImageOps

svg, out = sys.argv[1], sys.argv[2]
H = int(sys.argv[3]) if len(sys.argv) > 3 else 256

png = subprocess.run(["rsvg-convert", "-b", "white", "-w", "3000", svg],
                     check=True, capture_output=True).stdout
im = Image.open(io.BytesIO(png)).convert("L")
bbox = ImageOps.invert(im).point(lambda v: 255 if v > 8 else 0).getbbox()
im = im.crop(bbox)
W = round(im.width * H / im.height)
im = im.resize((W, H), Image.LANCZOS)
px = im.load()

data = bytearray()
for y in range(H):
    ccolor, cur = 1, 0
    for x in range(W):
        c = 1 if px[x, y] > 128 else 0
        if c != ccolor:
            data.append(cur)
            cur, ccolor = 1, c
        elif cur == 255:
            data += bytes([255, 0])
            cur = 1
        else:
            cur += 1
    if cur:
        data.append(cur)

# self-check: every row must sum to W
p = 0
for y in range(H):
    x = 0
    while x < W:
        x += data[p]; p += 1
    assert x == W, (y, x)
assert p == len(data)

b64 = base64.b64encode(bytes(data)).decode()
lines = textwrap.wrap(b64, 100)
with open(out, "w") as f:
    f.write("/*\n * GraVT X64 PROM splash, generated by tools/gravt_to_spans.py from\n"
            " * GraVT-src.svg at %d pixels tall (aspect preserved).\n *\n"
            " * Span encoding matches the original SGI stand/arcs/scripts/graytospans.c\n"
            " * contract.  The encoded rows are conventional top-to-bottom; the X64\n"
            " * product boundary reverses them once for original SGI drawCalligraphy().\n"
            " */\n\n" % H)
    f.write("unsigned char clogo_data[%d];\nint clogo_w = %d;\nint clogo_h = %d;\n\n"
            % (len(data), W, H))
    f.write("const char ArcsProductLogoBase64[] =\n")
    f.write("\n".join('    "%s"' % l for l in lines) + ";\n\n")
    f.write("const unsigned int ArcsProductLogoDecodedSize = %d;\n" % len(data))
print("W=%d H=%d bytes=%d" % (W, H, len(data)))
