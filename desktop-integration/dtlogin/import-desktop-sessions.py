#!/usr/bin/python3
"""Expose XDG .desktop sessions in the CDE dtlogin alternative-sessions menu."""
import argparse
import configparser
from pathlib import Path
import re
import shlex
import sys

PREFIX = "7000.xdg-session-"
LAUNCHER = "/usr/local/libexec/dtlogin-desktop-session"


def read_entry(path: Path) -> tuple[str, bool]:
    parser = configparser.ConfigParser(interpolation=None, strict=False)
    parser.optionxform = str
    with path.open(encoding="utf-8") as stream:
        parser.read_file(stream)
    desktop = parser["Desktop Entry"]
    return desktop.get("Name", path.stem), desktop.get("Hidden", "false").lower() == "true"


def output_for(name: str, path: Path) -> str:
    start = f"{LAUNCHER} --desktop-file {shlex.quote(str(path.resolve()))}"
    return (
        "! Generated from XDG session desktop entries; do not edit.\n"
        "Dtlogin*altDtsIncrement: True\n"
        f"Dtlogin*altDtName: {name.replace(chr(10), ' ').replace(chr(13), ' ')}\n"
        f"Dtlogin*altDtKey: {path.resolve()}\n"
        f"Dtlogin*altDtStart: {start}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--session-dir", action="append", type=Path, default=[])
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--launcher", type=Path, default=Path(LAUNCHER))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    entries: dict[str, tuple[Path, str]] = {}
    roots = args.session_dir or [Path("/usr/share/xsessions"), Path("/usr/local/share/xsessions")]
    for root in roots:
        if not root.is_dir():
            continue
        for path in sorted(root.glob("*.desktop")):
            try:
                name, hidden = read_entry(path)
            except (OSError, KeyError, configparser.Error, UnicodeError) as exc:
                print(f"skip {path}: {exc}", file=sys.stderr)
                continue
            # CDE's native session remains the classic default; the generated
            # entry is only needed for sessions that have an XDG desktop file.
            if hidden or path.stem == "cde":
                continue
            parser = configparser.ConfigParser(interpolation=None, strict=False)
            parser.optionxform = str
            with path.open(encoding="utf-8") as stream:
                parser.read_file(stream)
            if parser["Desktop Entry"].get("NoDisplay", "false").lower() == "true":
                continue
            entries[path.stem] = (path, name)
    if args.dry_run:
        for key, (path, name) in entries.items():
            print(f"[{key}] {name}: {path}")
        return 0
    if not args.launcher.is_file():
        print(f"missing session launcher: {args.launcher}", file=sys.stderr)
        return 2
    args.output_dir.mkdir(parents=True, exist_ok=True)
    expected = set()
    for key, (path, name) in entries.items():
        safe = re.sub(r"[^A-Za-z0-9_.-]+", "_", key)
        target = args.output_dir / f"{PREFIX}{safe}.session"
        target.write_text(output_for(name, path), encoding="utf-8")
        expected.add(target.name)
    # Remove only files generated by this importer, leaving classic CDE and
    # administrator-authored alternative-session resources untouched.
    for stale in args.output_dir.glob(f"{PREFIX}*.session"):
        if stale.name not in expected:
            stale.unlink()
    print(f"Imported {len(entries)} .desktop sessions into {args.output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
